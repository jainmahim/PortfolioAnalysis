"""
Offline maintenance script to regenerate utils/stock_universe.py from NSE's
published equity list.

This is NOT imported or run by the Streamlit app — the app always uses the
static NSE_STOCK_UNIVERSE list so the screener dropdown has no runtime
dependency on an external source being reachable. Run this script manually,
periodically (e.g. every few months), to pick up newly listed/delisted
symbols, then commit the regenerated utils/stock_universe.py.

Usage:
    python scripts/refresh_stock_universe.py

Requires network access to NSE's archives. Uses `requests` (already pulled in
transitively by yfinance) and the stdlib `csv` module; no new dependency is
introduced.
"""
import csv
import io
import sys
from pathlib import Path

import requests

# Official NSE-published list of all listed equities (symbol, name, series, ...).
NSE_EQUITY_LIST_URL = "https://archives.nseindia.com/content/equities/EQUITY_L.csv"

OUTPUT_PATH = Path(__file__).resolve().parent.parent / "utils" / "stock_universe.py"

FILE_TEMPLATE = '''import streamlit as st

# A comprehensive, static list of NSE tickers to ensure reliability.
# This replaces the need for a live API call for the universe and is much larger.
# Regenerated by scripts/refresh_stock_universe.py from NSE's published equity list.
# Do not edit by hand; re-run the script instead.
NSE_STOCK_UNIVERSE = sorted([
{tickers}
])


def get_stock_universe():
    """
    Returns a comprehensive, static list of all traded stocks from the NSE.
    This is faster and more reliable than a live API call.
    """
    return NSE_STOCK_UNIVERSE
'''


def fetch_nse_symbols() -> list[str]:
    # NSE requires a browser-like User-Agent or it rejects the request.
    headers = {"User-Agent": "Mozilla/5.0"}
    response = requests.get(NSE_EQUITY_LIST_URL, headers=headers, timeout=30)
    response.raise_for_status()

    reader = csv.DictReader(io.StringIO(response.text))
    if reader.fieldnames is None or "SYMBOL" not in [f.strip() for f in reader.fieldnames]:
        raise ValueError(f"Unexpected NSE CSV format; columns were: {reader.fieldnames}")

    symbol_key = next(f for f in reader.fieldnames if f.strip() == "SYMBOL")
    symbols = sorted({row[symbol_key].strip() for row in reader if row.get(symbol_key)})
    return symbols


def render_file(symbols: list[str]) -> str:
    # 8 tickers per line, double-quoted, matching the existing file's style.
    lines = []
    for i in range(0, len(symbols), 8):
        chunk = symbols[i : i + 8]
        line = "    " + ", ".join(f'"{s}"' for s in chunk) + ","
        lines.append(line)
    # Drop the trailing comma on the very last line.
    if lines:
        lines[-1] = lines[-1].rstrip(",")
    return FILE_TEMPLATE.format(tickers="\n".join(lines))


def main() -> int:
    try:
        symbols = fetch_nse_symbols()
    except Exception as e:
        print(f"Failed to fetch NSE equity list: {e}", file=sys.stderr)
        return 1

    if not symbols:
        print("Fetched zero symbols; refusing to overwrite stock_universe.py", file=sys.stderr)
        return 1

    content = render_file(symbols)
    OUTPUT_PATH.write_text(content)
    print(f"Wrote {len(symbols)} NSE symbols to {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
